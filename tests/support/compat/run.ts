/** Live compatibility run: `bun tests/support/compat/run.ts <service> [scenario,...]`. Anonymous; saves nothing. */
import { mkdirSync, writeFileSync } from "node:fs";
import { BrowserManager } from "../../../src/core/browser.ts";
import { endpoints, vendorServiceCode } from "../../../src/core/endpoints.ts";
import { runScenario, type Catalog, type Result, type Scenario } from "./replay.ts";

export function formatCompatReport(
  service: string,
  region: string,
  results: Result[],
  notes: string[] = []
): string {
  const cell = (r: Result) =>
    (r.blocker
      ? `BLOCKER: ${r.blocker}`
      : r.message ??
        (r.diff
          ? r.diff
              .map(
                (d) =>
                  `${d.key}: builder ${JSON.stringify(d.builder)} page ${JSON.stringify(d.page)}`
              )
              .join("; ")
          : ""))
      .replaceAll("|", "/")
      .slice(0, 300);

  return [
    `# ${service} compatibility (${region}, ${new Date().toISOString().slice(0, 10)})`,
    "",
    "Generated by `tests/support/compat/run.ts`.",
    "",
    "| scenario | region | result | stage | detail |",
    "|---|---|---|---|---|",
    ...results.map(
      (r) =>
        `| ${r.name} | ${r.effectiveRegion ?? region} | ${r.ok ? "ok" : r.stage === "blocked" ? "BLOCKED" : "FAIL"} | ${r.stage} | ${cell(r)} |`
    ),
    "",
    ...(notes.length ? ["## Not quotable", "", ...notes.map((n) => `- ${n}`), ""] : []),
  ].join("\n");
}

if (import.meta.main) {
  const [service, only] = [process.argv[2], process.argv[3]?.split(",")];
  if (!service) throw new Error("usage: run.ts <service> [scenario,...]");
  const region = process.env.AUTOCALC_REGION ?? "sa-brazil-1";
  const { scenarios, notes = [] } = (await import(`./scenarios/${service}.ts`)) as {
    scenarios: Scenario[];
    notes?: string[];
  };
  const catalogs = new Map<string, Catalog>();
  const catalogOf = async (r: string) =>
    catalogs.get(r) ??
    catalogs
      .set(
        r,
        await fetch(endpoints.cdnProduct(vendorServiceCode(service), r))
          .then((x) => x.json() as Promise<Catalog>)
          .catch(() => ({ product: {} }))
      )
      .get(r)!; // recipe services need no catalog
  const manager = new BrowserManager({ headed: false });
  const results: Result[] = [];
  try {
    for (const scenario of scenarios.filter((s) => !only || only.includes(s.name))) {
      // one at a time: parallel publishes overload the page
      const r = scenario.region ?? region;
      const result = await runScenario(manager, service, r, await catalogOf(r), scenario);
      results.push(result);
      console.log(JSON.stringify(result));
    }
  } finally {
    await manager.close();
  }

  // Preserve per-region reports
  const resultsByRegion = new Map<string, Result[]>();
  for (const r of results) {
    const reg = r.effectiveRegion ?? region;
    if (!resultsByRegion.has(reg)) resultsByRegion.set(reg, []);
    resultsByRegion.get(reg)!.push(r);
  }

  for (const [reg, regResults] of resultsByRegion) {
    mkdirSync(`docs/compat/${reg}`, { recursive: true });
    writeFileSync(
      `docs/compat/${reg}/${service}.md`,
      formatCompatReport(service, reg, regResults, notes)
    );
  }

  // Also write/update summary at docs/compat/${service}.md
  mkdirSync("docs/compat", { recursive: true });
  writeFileSync(
    `docs/compat/${service}.md`,
    formatCompatReport(service, region, results, notes)
  );

  if (results.some((r) => !r.ok)) {
    process.exitCode = 1;
  }
}
