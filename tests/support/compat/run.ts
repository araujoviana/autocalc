/** Live compatibility run: `bun tests/support/compat/run.ts <service> [scenario,...]`. Anonymous; saves nothing. */
import { mkdirSync, writeFileSync } from "node:fs";
import { BrowserManager } from "../../../src/core/browser.ts";
import { endpoints } from "../../../src/core/endpoints.ts";
import { runScenario, type Catalog, type Result, type Scenario } from "./replay.ts";

const [service, only] = [process.argv[2], process.argv[3]?.split(",")];
if (!service) throw new Error("usage: run.ts <service> [scenario,...]");
const region = process.env.AUTOCALC_REGION ?? "sa-brazil-1";
const { scenarios, notes = [] } = await import(`./scenarios/${service}.ts`) as { scenarios: Scenario[]; notes?: string[] };
const catalogs = new Map<string, Catalog>();
const catalogOf = async (r: string) => catalogs.get(r) ?? catalogs.set(r, await (await fetch(endpoints.cdnProduct(service, r))).json() as Catalog).get(r)!;
const manager = new BrowserManager({ headed: false });
const results: Result[] = [];
try {
  for (const scenario of scenarios.filter(s => !only || only.includes(s.name))) { // one at a time: parallel publishes overload the page
    const r = scenario.region ?? region, result = await runScenario(manager, service, r, await catalogOf(r), scenario);
    results.push(result); console.log(JSON.stringify(result));
  }
} finally { await manager.close(); }
const cell = (r: Result) => (r.message ?? (r.diff ? r.diff.map(d => `${d.key}: builder ${JSON.stringify(d.builder)} page ${JSON.stringify(d.page)}`).join("; ") : "")).replaceAll("|", "/");
mkdirSync("docs/compat", { recursive: true });
writeFileSync(`docs/compat/${service}.md`, [`# ${service} compatibility (${region}, ${new Date().toISOString().slice(0, 10)})`, "", "Generated by `tests/support/compat/run.ts`.", "", "| scenario | result | stage | detail |", "|---|---|---|---|",
  ...results.map(r => `| ${r.name} | ${r.ok ? "ok" : "FAIL"} | ${r.stage} | ${cell(r)} |`), "", ...(notes.length ? ["## Not quotable", "", ...notes.map(n => `- ${n}`), ""] : [])].join("\n"));
