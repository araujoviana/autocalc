/** Wire Budgeting, Title Sanitization, and Lean Card Payload Optimizer.
 * Enforces pre-flight byte constraints (< 950 KiB), card limits (<= 200),
 * clean list titles (<= 55 chars, zero autocalc watermarks), and lean payloads. */
import { CalculatorError } from "../errors.ts";
import { isFixedBaseCostService } from "./anti-split.ts";
import type { CanonicalResourceIR } from "./ir.ts";

/** Safe headroom threshold below Huawei Cloud's ~1 MiB HTTP 413 limit. */
export const MAX_LIST_BYTES = 950 * 1024; // 972,800 bytes

/** Safe card limit per saved shopping list to avoid portal DOM crashes. */
export const MAX_LIST_CARDS = 200;

/** Upstream list title length limit (~60 chars fails with opaque UPSTREAM error). */
export const MAX_TITLE_LENGTH = 55;

/** Forbids any tool branding or automated watermarking in user-visible titles. */
const WATERMARK_PATTERNS = [
  /\[\s*autocalc\s*\]/i,
  /\(\s*autocalc\s*\)/i,
  /generated by autocalc/i,
  /\bautocalc[:_-]?/i,
];

/** Measures exact serialized UTF-8 bytes as sent over HTTP JSON wire. */
export function measureCompactBytes(payload: unknown): number {
  const json = JSON.stringify(payload);
  return new TextEncoder().encode(json).length;
}

/** Sanitizes and enforces length limits on card and list titles with zero tool watermarking. */
export function sanitizeTitle(rawTitle: string, maxLength = MAX_TITLE_LENGTH): string {
  let cleaned = rawTitle.trim();

  // Strip automated tool watermarks
  for (const pat of WATERMARK_PATTERNS) {
    cleaned = cleaned.replace(pat, "").trim();
  }

  // Remove empty brackets and leftover punctuation/dashes
  cleaned = cleaned.replace(/\[\s*\]|\(\s*\)/g, "").trim();
  cleaned = cleaned.replace(/^[\s\-_:.]+|[\s\-_:.]+$/g, "").trim();

  if (!cleaned) {
    cleaned = "Quote";
  }

  if (cleaned.length > maxLength) {
    cleaned = cleaned.slice(0, maxLength).trim();
  }

  return cleaned;
}

/** Validates that a proposed list title complies with length and zero-watermark rules. */
export function validateListTitle(title: string): void {
  if (title.length > MAX_TITLE_LENGTH) {
    throw new CalculatorError(
      "VALIDATION",
      `List title '${title}' exceeds maximum length of ${MAX_TITLE_LENGTH} characters (${title.length} chars).`
    );
  }

  for (const pat of WATERMARK_PATTERNS) {
    if (pat.test(title)) {
      throw new CalculatorError(
        "VALIDATION",
        `List title '${title}' contains forbidden tool watermark. List titles belong 100% to the user.`
      );
    }
  }
}

export interface ShardPartition {
  index: number;
  title: string;
  resources: CanonicalResourceIR[];
  cardCount: number;
  estimatedBytes: number;
}

/** Partitions an array of canonical resources into shards that strictly respect byte and card limits. */
export function partitionResources(
  resources: CanonicalResourceIR[],
  titlePrefix = "Quote",
  maxCards = MAX_LIST_CARDS,
  maxBytes = MAX_LIST_BYTES
): ShardPartition[] {
  const shards: ShardPartition[] = [];
  let currentResources: CanonicalResourceIR[] = [];
  let currentCards = 0;
  let currentBytes = 0;

  const pushCurrentShard = () => {
    if (currentResources.length === 0) return;
    const shardIndex = shards.length;
    const suffix = shards.length > 0 || resources.length > currentResources.length ? ` - Part ${shardIndex + 1}` : "";
    const title = sanitizeTitle(`${titlePrefix}${suffix}`, MAX_TITLE_LENGTH);

    shards.push({
      index: shardIndex,
      title,
      resources: currentResources,
      cardCount: currentCards,
      estimatedBytes: currentBytes,
    });

    currentResources = [];
    currentCards = 0;
    currentBytes = 0;
  };

  for (const res of resources) {
    const cardCount = res.physicalCards.length;
    const approxBytes = measureCompactBytes(res.physicalCards);

    // If adding this resource would exceed card count or byte limit, start new shard
    if (
      currentResources.length > 0 &&
      (currentCards + cardCount > maxCards || currentBytes + approxBytes > maxBytes)
    ) {
      pushCurrentShard();
    }

    currentResources.push(res);
    currentCards += cardCount;
    currentBytes += approxBytes;
  }

  pushCurrentShard();
  return shards;
}

/** Optimizes a vendor card payload by pruning zero-usage lines and foreign bakPlanList plans. */
export function optimizeCardPayload(card: Record<string, any>): Record<string, any> {
  if (!Array.isArray(card.productAllInfos)) {
    return card;
  }

  const optimizedInfos = card.productAllInfos.map((info: Record<string, any>) => {
    if (!Array.isArray(info.bakPlanList)) {
      return info;
    }

    // Keep only plans corresponding to this line's own usage factor
    const ownFactor = info.usageFactor;
    const leanPlans = info.bakPlanList.filter((plan: Record<string, any>) =>
      !ownFactor || plan.usageFactor === ownFactor
    );

    return {
      ...info,
      bakPlanList: leanPlans.length > 0 ? leanPlans : info.bakPlanList,
    };
  });

  return {
    ...card,
    productAllInfos: optimizedInfos,
  };
}
